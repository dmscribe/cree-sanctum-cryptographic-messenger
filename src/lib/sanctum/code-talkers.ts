function cleanWord(w: string): string {
  return w.toLowerCase().replace(/[^a-z]/g, "");
}

export const TALKER_LIST: readonly string[] = (() => {
  const out: string[] = [];
  const seen = new Set<string>();
  for (const raw of TALKER_WORDS) {
    const w = cleanWord(raw);
    if (w.length < 3 || seen.has(w)) continue;
    seen.add(w);
    out.push(w);
  }
  if (out.length < 256) {
    throw new Error(`code-talker list is ${out.length}, need 256`);
  }
  return out.slice(0, 256);
})();

export const TALKER_COUNT = TALKER_LIST.length;
export const TALKER_PHRASE_WORDS = 16;
